#!/usr/bin/env node
// Turns content/categories.json into
//   1. supabase/seed/catalog.sql: an idempotent upsert of the built-in categories (HANDOFF §12).
//      It never touches daily_puzzles. A built-in category dropped from the file is set inactive, never deleted.
//   2. the bundled catalog block in index.html, used when the server has no categories.
// Usage: node tools/catalog-to-sql.mjs [content/categories.json]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { validate } from './validate-categories.mjs';

const file = process.argv[2] || 'content/categories.json';
const cats = JSON.parse(readFileSync(file, 'utf8'));
const { errors } = validate(cats);
if (errors.length) {
  for (const e of errors) console.error(`ERROR    ${e}`);
  console.error('Fix these first (node tools/validate-categories.mjs).');
  process.exit(1);
}

// Same shape the client and get_catalog use: est is a share (0-1), not a percent.
const rows = cats.map(c => ({
  slug: c.id, name: c.label, title: c.title, grp: c.group, sub: c.sub, kind: c.kind, season: c.season,
  opts: c.opts.map(([name, pct]) => ({ name, est: pct / 100 })),
  clues: c.clues
}));

const q = s => s === null ? 'null' : `'${String(s).replace(/'/g, "''")}'`;
const j = v => `${q(JSON.stringify(v))}::jsonb`;
const values = rows.map(r => `  (${q(r.slug)}, ${q(r.name)}, ${q(r.title)}, ${q(r.grp)}, ${q(r.sub)}, ${q(r.kind)}, ${q(r.season)}, ${j(r.opts)}, ${j(r.clues)}, 'builtin', true)`).join(',\n');

const sql = `-- Generated by tools/catalog-to-sql.mjs from ${file}. Do not edit by hand.
-- Upserts the ${rows.length} built-in categories by slug. Safe to run more than once.
-- Never touches daily_puzzles: published puzzles keep the snapshot they were frozen with.
begin;

insert into public.catalog (slug, name, title, grp, sub, kind, season, opts, clues, source, active)
values
${values}
on conflict (slug) do update
  set name = excluded.name, title = excluded.title, grp = excluded.grp, sub = excluded.sub, kind = excluded.kind, season = excluded.season,
      opts = excluded.opts, clues = excluded.clues, active = true, updated_at = now()
  where public.catalog.source = 'builtin';

-- A built-in category removed from the file is retired, not deleted (votes and history stay).
update public.catalog set active = false, updated_at = now()
 where source = 'builtin' and active
   and slug not in (${rows.map(r => q(r.slug)).join(', ')});

commit;
`;
mkdirSync('supabase/seed', { recursive: true });
writeFileSync('supabase/seed/catalog.sql', sql);

// Starter takes (D-31): content/takes.json -> supabase/seed/takes.sql. Replaces every starter take; player takes are untouched.
const takesFile = 'content/takes.json';
const takes = JSON.parse(readFileSync(takesFile, 'utf8'));
const slugs = new Set(rows.map(r => r.slug));
const trows = [];
for (const [slug, list] of Object.entries(takes)) {
  if (!slugs.has(slug)) { console.error(`${takesFile}: "${slug}" isn't a category`); process.exit(1); }
  for (const t of list) {
    const bad = !t || typeof t.author !== 'string' || t.author.length < 1 || t.author.length > 24
      || typeof t.pick !== 'string' || t.pick.length < 1 || t.pick.length > 40
      || typeof t.reason !== 'string' || t.reason.length < 2 || t.reason.length > 280;
    if (bad) { console.error(`${takesFile}: bad take in "${slug}": ${JSON.stringify(t)}`); process.exit(1); }
    trows.push(`  (${q(slug)}, ${q(t.author)}, ${q(t.pick)}, ${q(t.reason)}, true)`);
  }
}
writeFileSync('supabase/seed/takes.sql', `-- Generated by tools/catalog-to-sql.mjs from ${takesFile}. Do not edit by hand.
-- Replaces the ${trows.length} starter takes (seed = true). Player takes are never touched. Run after catalog.sql.
begin;
delete from public.takes where seed;
insert into public.takes (slug, author, pick, reason, seed)
values
${trows.join(',\n')};
commit;
`);

const html = readFileSync('index.html', 'utf8');
const re = /(<script type="application\/json" id="bundled-catalog">)[\s\S]*?(<\/script>)/;
if (!re.test(html)) { console.error('index.html has no bundled-catalog block'); process.exit(1); }
const bundled = JSON.stringify(rows).replace(/</g, '\\u003c');
writeFileSync('index.html', html.replace(re, (_, a, b) => a + bundled + b));

console.log(`${rows.length} categories -> supabase/seed/catalog.sql and index.html; ${trows.length} starter takes -> supabase/seed/takes.sql`);
